const Version = "oob-pir-v1"

// Public is public.json: everything a client needs besides the hint.
type Public struct {
	Version      string `json:"version"`
	Scheme       string `json:"scheme"`
	Upstream     string `json:"upstream"`
	EpochID      string `json:"epoch_id"`
	Layout       Layout `json:"layout"`
	SeedA        string `json:"seed_A"`
	ADerivation  string `json:"a_derivation"`
	Encoding     string `json:"encoding"`
	HintFile     string `json:"hint_file"`
	HintBytes    uint64 `json:"hint_bytes"`
	HintSHA256   string `json:"hint_sha256"`
	QueryBytes   uint64 `json:"query_bytes"`
	AnswerBytes  uint64 `json:"answer_bytes"`
	ADownloadAlt uint64 `json:"a_bytes_if_downloaded"`
}

const (
	UpstreamRev = "github.com/ahenzinger/simplepir@e9020b03bf2872c75b8954e749e32408b5db87ed"
	ADerivDesc  = "upstream compressed-state expansion (SimplePIR.DecompressState algorithm): AES-128-CTR(key=seed_A[0:16], iv=0) via 8192-B XOR-refilled buffer, entries = successive big-endian uint32, row-major m x n; regenerated by client, never downloaded"
	EncDesc     = "record bits little-endian; chunks of chunk_bits bits -> digits_per_chunk base-p digits (LSB first); record i in column i%m, rows (i/m)*Ne .. +Ne; DB entry = digit - floor(p/2) mod 2^32 before Setup (as upstream MakeDB)"
)

type Server struct {
	Layout  Layout
	EpochID string
	SeedA   []byte
	db      *pir.Database
	params  pir.Params
}

type SetupStats struct {
	EpochID          string  `json:"epoch_id"`
	HintBytes        uint64  `json:"hint_bytes"`
	PublicBytes      uint64  `json:"public_bytes"`
	SetupSeconds     float64 `json:"setup_seconds"`
	EncodeSeconds    float64 `json:"encode_seconds"`
	AGenSeconds      float64 `json:"a_expand_seconds"`
	HintSeconds      float64 `json:"hint_seconds"` // upstream Setup: H = DB*A + squish
	WriteSeconds     float64 `json:"write_seconds"`
	DBPayloadBytes   uint64  `json:"db_payload_bytes"`
	DBMatrixBytes    uint64  `json:"db_matrix_bytes_unpacked"`
	PackedDBBytes    uint64  `json:"packed_db_bytes"`
	ABytesIfDownload uint64  `json:"a_bytes_if_downloaded"`
	SeedBytes        uint64  `json:"seed_bytes"`
	HintSHA256       string  `json:"hint_sha256"`
	HintFile         string  `json:"hint_file"`
	PublicFile       string  `json:"public_file"`
	Layout           Layout  `json:"layout"`
	Preprocessing    string  `json:"preprocessing"`
}

// NewServer runs full upstream preprocessing over the real records:
// DB matrix from the records, A from seed_A, pi.Setup (hint = DB*A over the
// whole DB, then squish). records must be count*width bytes.
func NewServer(records []byte, count, width, cols uint64, seedA []byte, epochID string) (*Server, []byte, *SetupStats, error) {
	if width != RecordWidth {
		return nil, nil, nil, errors.New("width must be 736")
	}
	if uint64(len(records)) != count*width {
		return nil, nil, nil, errors.New("records length != count*width")
	}
	lay, err := ChooseLayout(count, width, cols)
	if err != nil {
		return nil, nil, nil, err
	}
	st := &SetupStats{EpochID: epochID, Layout: lay, DBPayloadBytes: count * width,
		ABytesIfDownload: lay.ABytes(), SeedBytes: 32,
		Preprocessing: "full: upstream SimplePIR.Setup over the real DB (H = DB*A), no FakeSetup"}
	t0 := time.Now()
	D := pir.MatrixZeros(lay.L, lay.M)
	d := u32(D)
	half := uint32(lay.P / 2)
	for i := range d { // empty slots = digit 0, mapped like upstream MakeDB (database.go:211)
		d[i] = -half
	}
	digits := make([]uint32, lay.Ne)
	for i := uint64(0); i < count; i++ {
		lay.RecordDigits(records[i*width:(i+1)*width], digits)
		col := i % lay.M
		base := (i / lay.M) * lay.Ne
		for t, v := range digits {
			d[(base+uint64(t))*lay.M+col] = v - half
		}
	}
	st.EncodeSeconds = time.Since(t0).Seconds()
	st.DBMatrixBytes = uint64(len(d)) * 4

	t1 := time.Now()
	A, err := ExpandA(seedA, lay.M, lay.N)
	if err != nil {
		return nil, nil, nil, err
	}
	st.AGenSeconds = time.Since(t1).Seconds()

	t2 := time.Now()
	DB := &pir.Database{Info: lay.Info(), Data: D}
	DB.Info.Basis, DB.Info.Squishing, DB.Info.Cols = 0, 0, 0
	var pi pir.SimplePIR
	params := lay.Params()
	_, hintMsg := pi.Setup(DB, pir.MakeState(A), params)
	st.HintSeconds = time.Since(t2).Seconds()
	DB.Data.Data = padCap(DB.Data.Data, 8*int(DB.Data.Cols))
	st.PackedDBBytes = uint64(len(DB.Data.Data)) * 4
	hint := hintMsg.Data[0]
	if hint.Rows != lay.L || hint.Cols != lay.N {
		return nil, nil, nil, errors.New("internal: hint dims")
	}
	hb := EncodeHint(hint)
	sum := sha256.Sum256(hb)
	st.HintSHA256 = hex.EncodeToString(sum[:])
	st.HintBytes = uint64(len(hb))
	st.SetupSeconds = time.Since(t0).Seconds()
	A, D, hint, hintMsg = nil, nil, nil, pir.Msg{}
	runtime.GC()
	s := &Server{Layout: lay, EpochID: epochID, SeedA: append([]byte(nil), seedA...), db: DB, params: params}
	return s, hb, st, nil
}

func (s *Server) Public(hintFile string, hb []byte, sum string) Public {
	return Public{Version: Version, Scheme: "SimplePIR", Upstream: UpstreamRev, EpochID: s.EpochID,
		Layout: s.Layout, SeedA: hex.EncodeToString(s.SeedA), ADerivation: ADerivDesc, Encoding: EncDesc,
		HintFile: hintFile, HintBytes: uint64(len(hb)), HintSHA256: sum,
		QueryBytes: s.Layout.QueryBytes(), AnswerBytes: s.Layout.AnswerBytes(), ADownloadAlt: s.Layout.ABytes()}
}

// WriteFiles writes hint.bin and public.json to outDir.
func (s *Server) WriteFiles(outDir string, hb []byte, st *SetupStats) error {
	t := time.Now()
	if err := os.MkdirAll(outDir, 0o755); err != nil {
		return err
	}
	hp := filepath.Join(outDir, "hint.bin")
	if err := os.WriteFile(hp, hb, 0o644); err != nil {
		return err
	}
	pub := s.Public("hint.bin", hb, st.HintSHA256)
	pj, _ := json.MarshalIndent(pub, "", " ")
	pp := filepath.Join(outDir, "public.json")
	if err := os.WriteFile(pp, pj, 0o644); err != nil {
		return err
	}
	st.PublicBytes = uint64(len(pj))
	st.HintFile, st.PublicFile = hp, pp
	st.WriteSeconds = time.Since(t).Seconds()
	return nil
}

// Answer runs upstream SimplePIR.Answer on a canonical binary query.
func (s *Server) Answer(q []byte) ([]byte, error) {
	v, err := decodeVec(queryMagic, q, s.Layout.QueryLen)
	if err != nil {
		return nil, err
	}
	qm := pir.MatrixNew(s.Layout.QueryLen, 1)
	copy(u32(qm), v)
	var pi pir.SimplePIR
	ans := pi.Answer(s.db, pir.MakeMsgSlice(pir.MakeMsg(qm)), pir.MakeState(), pir.MakeState(), s.params)
	a := ans.Data[0]
	if a.Rows != s.Layout.L || a.Cols != 1 {
		return nil, errors.New("internal: answer dims")
	}
	return encodeVec(answerMagic, u32(a)), nil
}

// PublicBytes is the size of public.json for this layout (as WriteFiles writes it).
func PublicBytes(lay Layout, epochID string) uint64 {
	s := &Server{Layout: lay, EpochID: epochID, SeedA: make([]byte, 32)}
	pj, _ := json.MarshalIndent(s.Public("hint.bin", make([]byte, lay.HintBytes()), hex.EncodeToString(make([]byte, 32))), "", " ")
	return uint64(len(pj))
}
