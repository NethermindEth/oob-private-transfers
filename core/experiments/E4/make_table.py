#!/usr/bin/env python3
"""Generate core/results/E4/e4_admission.tex (LaTeX tabular BODY only) and a Markdown table from raw
E4 result files. Usage: make_table.py [results_dir]   (default: newest non-quick core/results/E4/<ts>/)"""
import glob, json, os, statistics, sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..', '..'))
RES = os.path.join(ROOT, 'core', 'results', 'E4')


def newest():
    ds = sorted(d for d in glob.glob(os.path.join(RES, '2*')) if os.path.isdir(d) and not d.endswith('-quick'))
    if not ds:
        sys.exit('no results')
    return ds[-1]


def rows(d):
    out = []
    for f in sorted(glob.glob(os.path.join(d, '*.json'))):
        if f.endswith('.bench.json') or f.endswith('run_meta.json'):
            continue
        rec = json.load(open(f))
        r = rec.get('result')
        if not r or r.get('mode') != 'bench':
            continue
        s = [x for x in r['samples'] if x['valid']]
        pv = [x['prove_seconds'] for x in s]
        vv = [x['verify_seconds'] * 1e3 for x in s]
        pb = sorted({x['proof_bytes'] for x in s})
        st = r['setup']
        params_s = st['params_generate_seconds_fresh']
        if params_s is None:
            params_s = st['params_seconds_this_run'] if st['params_source_this_run'] == 'generated' else None
        setup = None if params_s is None else params_s + st['keygen_vk_seconds'] + st['keygen_pk_seconds']
        out.append(dict(
            name=rec['name'], variant=r['variant'], depth=r['depth'], k=r['k'], threads=r['rayon_threads'],
            n=len(pv), failures=len(r['failures']), setup=setup, params_s=params_s,
            vk_s=st['keygen_vk_seconds'], pk_s=st['keygen_pk_seconds'],
            prove_med=statistics.median(pv), prove_min=min(pv), prove_max=max(pv),
            verify_med=statistics.median(vv), verify_min=min(vv), verify_max=max(vv),
            proof_bytes=pb, rss_mb=rec['time_l'].get('max_rss_bytes', 0) / 2**20,
            contaminated=rec['contaminated'], rows=r['rows_used'], advice=r['advice_columns'],
            load=(rec['load_avg_start'][0], rec['load_avg_end'][0])))
    order = {'full': 0, 'weak': 1}
    out.sort(key=lambda x: (order[x['variant']], x['threads'] == 1, x['depth']))
    return out


def label(r):
    base = 'P1 (full binding)' if r['variant'] == 'full' else 'W1 (weak: digest only)'
    return base + (', 1 thread' if r['threads'] == 1 else '')


def main():
    d = sys.argv[1] if len(sys.argv) > 1 else newest()
    rs = rows(d)
    tex, md = [], []
    md.append('| Variant | Depth | k | Rows | Threads | Setup (s) | Prove (s, median [min–max]) | Verify (ms, median) | Proof (B) | Peak RSS (MB) | n |')
    md.append('|---|---|---|---|---|---|---|---|---|---|---|')
    for r in rs:
        setup = '--' if r['setup'] is None else f"{r['setup']:.1f}"
        pb = '/'.join(str(b) for b in r['proof_bytes'])
        flag = r'$^\dagger$' if r['contaminated'] else ''
        tex.append(f"{label(r)} & {r['depth']} & {r['k']} & {setup} & "
                   f"{r['prove_med']:.2f} [{r['prove_min']:.2f}--{r['prove_max']:.2f}] & "
                   f"{r['verify_med']:.1f} & {pb} & {r['rss_mb']:.0f}{flag} \\\\")
        md.append(f"| {label(r)} | {r['depth']} | {r['k']} | {r['rows']} | {r['threads']} | {setup} | "
                  f"{r['prove_med']:.2f} [{r['prove_min']:.2f}–{r['prove_max']:.2f}] | {r['verify_med']:.1f} | {pb} | "
                  f"{r['rss_mb']:.0f} | {r['n']}{' (contaminated)' if r['contaminated'] else ''} |")
    open(os.path.join(RES, 'e4_admission.tex'), 'w').write(
        f"% generated by core/experiments/E4/make_table.py from {os.path.relpath(d, ROOT)}\n" + '\n'.join(tex) + '\n')
    open(os.path.join(RES, 'e4_admission.md'), 'w').write(
        f"Source: `{os.path.relpath(d, ROOT)}`. Setup = Params::new(k) (fresh) + keygen_vk + keygen_pk.\n\n" + '\n'.join(md) + '\n')
    print('\n'.join(md))
    # adversarial summaries
    for f in sorted(glob.glob(os.path.join(d, 'adversarial_*.json'))):
        if f.endswith('.bench.json'):
            continue
        r = json.load(open(f)).get('result', {})
        print(os.path.basename(f), r.get('summary'))


if __name__ == '__main__':
    main()
