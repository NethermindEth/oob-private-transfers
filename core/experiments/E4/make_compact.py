"""Compact E4 table for the paper: reuses make_table.rows(); drops Setup/RSS/k columns (setup and RSS go in
the note). Usage: python make_compact.py <run_dir> -> core/results/E4/e4_admission_compact.tex (rows only)."""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from make_table import rows
d = sys.argv[1]
lines = [f"% generated by core/experiments/E4/make_compact.py from {d}"]
for r in rows(d):
    v = 'P1 full' if r['variant'] == 'full' else 'W1 weak'
    th = '1' if r['threads'] == 1 else str(r['threads'])
    flag = r'$^\dagger$' if r['contaminated'] else ''
    lines.append(f"{v} & {r['depth']} & {th} & {r['prove_med']:.2f} [{r['prove_min']:.2f}--{r['prove_max']:.2f}]{flag} & "
                 f"{r['verify_med']:.1f} & {'/'.join(str(b) for b in r['proof_bytes'])} & {r['n']} \\\\")
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', 'results', 'E4', 'e4_admission_compact.tex')
open(out, 'w').write("\n".join(lines) + "\n"); print("\n".join(lines))
