"""E6 tables (LaTeX tabular BODY only) from the latest raw file -> core/results/E6/e6_capacity.tex, e6_storage.tex"""
import json
import statistics as st
from pathlib import Path

R = Path(__file__).resolve().parents[2] / 'results/E6'


def latest():
    for f in sorted(R.glob('*/e6_raw.json'), reverse=True):
        d = json.loads(f.read_text())
        if 'read' in d and (not d['meta'].get('contaminated') or d['meta'].get('self_induced_load')):
            return f, d
    raise SystemExit('no usable E6 raw file')


def f2(x, n=2):
    return '--' if x is None else f'{x:.{n}f}'


def main():
    f, d = latest()
    rd = {r['K']: r for r in d['read']}
    ap = {r['K']: r for r in d['append_replay']}
    an = {r['K']: r for r in d['append_new']}
    rows = [
        'PIR reads/s (answer+decode, $2^{12}$ epoch) & ' + ' & '.join(f2(rd[k]['throughput_rps'], 1) for k in (1, 8, 32)) + ' \\\\',
        'PIR read latency median / p90 (s) & ' + ' & '.join(f"{f2(rd[k]['latency']['median_s'], 3)} / {f2(rd[k]['latency']['p90_s'], 3)}" for k in (1, 8, 32)) + ' \\\\',
        'Append req/s, verification-limited (replay) & ' + ' & '.join(f2(ap[k]['throughput_rps']) for k in (1, 8, 32)) + ' \\\\',
        'Append latency median / p90 (s) & ' + ' & '.join(f"{f2(ap[k]['latency']['median_s'])} / {f2(ap[k]['latency']['p90_s'])}" for k in (1, 8, 32)) + ' \\\\',
        'Append req/s, new records (insert path) & ' + ' & '.join(f2(an[k]['throughput_rps']) if k in an else '--' for k in (1, 8, 32)) + ' \\\\',
        f"Client proving proofs/s (1 worker; 4 workers) & {f2(d['proving_1_worker']['throughput_proofs_per_s'], 3)} & "
        f"{f2(d['proving_4_workers']['throughput_proofs_per_s'], 3)} (4) & -- \\\\",
        'Failures (reads / wrong records / appends) & ' + ' & '.join(
            f"{rd[k]['failures']}/{rd[k]['wrong_records']}/{sum(v for o, v in ap[k]['outcomes'].items() if o not in ('new', 'idempotent'))}" for k in (1, 8, 32)) + ' \\\\',
    ]
    head = ('% generated by core/experiments/E6/make_table.py from ' + str(f.relative_to(R.parents[1])) +
            f"; same-host 12-core laptop; {d['meta']['config']['verifier_workers']} verifier workers\n"
            'Metric & $c{=}1$ & $c{=}8$ & $c{=}32$ \\\\ \\hline\n')
    (R / 'e6_capacity.tex').write_text(head + '\n'.join(rows) + '\n')
    print((R / 'e6_capacity.tex').read_text())
    # ---------------- storage accounting per record (bytes), from measured files/status
    s = d['storage']
    ep = [e for e in s['epochs'] if e['m_e'] == 4096][-1]
    m = ep['m_e']
    hs = s['holders']
    frag = st.median([h['fragment_bytes'] for h in hs])  # all epochs held
    total_recs = s['provider_records']
    sq = sum(v for k, v in s['provider_files'].items() if k.startswith('provider.sqlite3'))
    per_rec_db = sq / total_recs
    hint_per_rec = ep['hint_bytes'] / m
    pirdb = (ep['pir_worker'] or {}).get('packed_db_bytes')
    holder_frag_per_rec = sum(h['fragment_bytes'] for h in hs) / total_recs
    leaf_per_rec = sum(h['leaf_bytes'] for h in hs) / total_recs
    mc_per_rec = sum(h['manifest_cert_bytes'] for h in hs) / total_recs
    seal_bw = ep.get('seal_bytes_sent')
    rows2 = [
        f'Active copy: SQLite (record, tag, index, receipt) & {per_rec_db:.0f} & $r\\times$ \\\\',
        f'PIR state: hint file / in-memory packed DB & {hint_per_rec:.0f} / {pirdb / m if pirdb else 0:.0f} & $r\\times$ \\\\',
        f'RS(3,5) fragments at 5 holders & {holder_frag_per_rec:.0f} & per certified copy \\\\',
        f'Holder leaf hashes + manifests/certs & {leaf_per_rec:.0f} + {mc_per_rec:.1f} & per certified copy \\\\',
        f'Full-copy backup to 3 holders (same 2-loss tolerance) & {3 * 736} & model \\\\',
        f'Sealing bandwidth (each holder gets the full epoch) & {seal_bw / m if seal_bw else 0:.0f} & vs {3 * 736} full-copy \\\\',
        f'Repair of one lost fragment (fetch k fragments) & {736 * 1:.0f} & vs 736 full-copy \\\\',
    ]
    e1s = sorted((R.parent / 'E1').glob('*/e1_raw.json'))
    if e1s:
        e1 = json.loads(e1s[-1].read_text())
        up = st.median([r['append']['attempts'][0]['bytes_up'] for r in e1['runs'] if r.get('ok')])
        per_copy = per_rec_db + hint_per_rec + holder_frag_per_rec + leaf_per_rec + mc_per_rec
        rows2.append('Total per note, $r{=}1/2/3$ copies: upload kB; stored B & ' +
                     ' / '.join(f'{r * up / 1e3:.1f}; {r * per_copy:.0f}' for r in (1, 2, 3)) + ' & $r$ independent copies \\\\')
    head2 = ('% generated by core/experiments/E6/make_table.py; bytes per 736-B record; measured files/status except rows marked model\n'
             'Item & bytes/record & scales with \\\\ \\hline\n')
    (R / 'e6_storage.tex').write_text(head2 + '\n'.join(rows2) + '\n')
    print((R / 'e6_storage.tex').read_text())


if __name__ == '__main__':
    main()
