"""Table: OOB (measured) vs direct delivery + encrypted RS(3,5) backup (MEASURED, run_backup.py). Replaces the
modeled comparison (core/experiments/E6/model_a9.py). Inputs: latest backup raw, latest E1 raw (sender upload,
policy read), latest E2 raw (recovery from 3 holders, principal 4096-record epoch).
Output: core/results/E5base/e5_backup.tex (tabular body) + e5_backup.json."""
import json
import statistics as st
from pathlib import Path

R = Path(__file__).resolve().parents[2] / 'results'


def latest(pattern):
    fs = sorted(R.glob(pattern))
    return fs[-1], json.loads(fs[-1].read_text())


def main():
    fb, b = latest('E5base/backup-*/backup_raw.json')
    f1, e1 = latest('E1/*/e1_raw.json')
    f2, e2 = latest('E2/*/e2_raw.json')
    big = next(x for x in b['buckets'] if x['m'] == 4096)['summary']
    runs = [r for r in e1['runs'] if r.get('ok')]
    up = st.median(r['append']['attempts'][0]['bytes_up'] for r in runs)
    dl = st.median(r['auto_read']['download_bytes'] for r in runs)
    ok3 = [r for r in e2['results'] if r['case']['id'] == 'ok3']
    rec3 = st.median(sum(e.get('fetch_bytes') or 0 for e in r['recovery']['epochs'].values()) for r in ok3)
    rows = [
        f"Sender upload per note & {up / 1e3:.1f}\\,kB (rec.\\ + proof) & {big['sender_upload_bytes'] / 1e3:.1f}\\,kB (msg.\\ + fragments) \\\\",
        f"Erasure-coded storage per note & 1,227\\,B (fragments) & {big['fragment_bytes']:,.0f}\\,B (fragments) \\\\",
        f"Private read, $m{{=}}4096$ & {dl / 1e6:.2f}\\,MB (epoch) & {big['recovery_whole_bucket_bytes'] / 1e6:.2f}\\,MB (bucket) \\\\",
        f"Recovery, 2 of 5 lost, $m{{=}}4096$ & {rec3 / 1e6:.2f}\\,MB (epoch) & {big['recovery_by_id_bytes']:,.0f}\\,B by id (not private) \\\\",
        "One slot per output (anonymous) & yes & no \\\\",
        "Stored bytes proven = committed note & yes & no \\\\",
        "Locators, dedup survive loss & yes & no service \\\\",
    ]
    head = (f"% generated by core/experiments/E5base/make_backup_table.py from {fb.relative_to(R.parent)}, "
            f"{f1.relative_to(R.parent)}, {f2.relative_to(R.parent)}; both columns MEASURED, same host\n"
            "Property & OOB & direct + EC backup \\\\ \\hline\n")
    (R / 'E5base' / 'e5_backup.tex').write_text(head + '\n'.join(rows) + '\n')
    (R / 'E5base' / 'e5_backup.json').write_text(json.dumps({'backup_4096': big, 'oob_upload': up, 'oob_download': dl,
                                                             'oob_recovery_3_holders': rec3}, indent=1))
    print((R / 'E5base' / 'e5_backup.tex').read_text())


if __name__ == '__main__':
    main()
