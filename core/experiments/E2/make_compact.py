"""Compact E2 table for the paper: all case types, from raw JSON only.
Usage: python make_compact.py <e2_raw.json> [<later e2_raw.json> ...] -> core/results/E2/e2_recovery_compact.tex (rows only).
Later files REPLACE all results of the case ids they contain.
Columns: case & outcome & recovery wall (s) & first private read after start (s) & fetched MB & reps"""
import json, statistics, sys, os
by = {}
for fn in sys.argv[1:]:
    new = {}
    for c in json.load(open(fn))['results']:
        new.setdefault(c['case']['id'], []).append(c)
    by.update(new)
def med(xs):
    xs = [x for x in xs if x is not None]
    return f"{statistics.median(xs):.2f}" if xs else "--"
def fetched(c):
    r = c.get('recovery') or {}
    b = sum((e.get('fetch_bytes') or 0) for e in (r.get('epochs') or {}).values())
    return b / 1e6
def outcome(cid, cs):
    c = cs[0]; r = c.get('recovery') or {}
    ok_reads = sum(1 for x in cs if (x.get('read') or {}).get('ok') or (x.get('refusal_read') or {}).get('ok'))
    re = [x for x in cs if (x.get('replay') or {}).get('outcome') == 'new' and (x.get('reappend_read') or {}).get('ok')]
    rel = [x for x in re if x.get('reappend_certified') and (x.get('reappend_release') or {}).get('released')]
    if rel:  # The re-appended record was certified at the replacement and the sender released it
        tail = "; re-app.\\ cert."
    else:
        tail = f"; re-app.\\ read, uncert.\\ ({len(re)}/{len(cs)})" if re else ''
    if cid in ('badack', 'inconsistent'):
        return ('never cert.' if tail else 'never certified') + tail
    if cid == 'precert':
        return 'lost here' + tail
    if cid == 'dropped':
        return 'incl.\\ fails' + tail
    if cid == 'holder_replaced' and ok_reads:
        return f"set replaced; recovered ({ok_reads}/{len(cs)})"
    if r.get('temporarily_unrecoverable'):
        return 'unrecoverable'
    if cid == 'refuse':
        v = (c.get('refusal_read') or {}).get('via', '?')
        return "read via holders" if v == "recipient_recovery" else f"read via {v}"
    return f"recovered ({ok_reads}/{len(cs)})"
LABEL = {'ok5': '5/5 holders', 'ok4': '4/5 holders', 'ok3': '3/5 holders', 'fail2': '2/5 holders',
         'corrupt1': '1 corrupt fragment', 'corrupt3': '3 corrupt fragments', 'dupcoord': '3 dup.\\ coordinates',
         'badack': 'invalid ack (seal)', 'inconsistent': 'non-codeword (seal)', 'precert': 'lost before cert.',
         'dropped': 'receipted rec.\\ dropped', 'refuse': 'live, refuses reads',
         'holder_replaced': '1 holder lost at seal', 'ok5_fresh': '5/5, no params cache',
         'sweep1': '1 epoch, $m_e{=}16$', 'sweep10': '10 epochs, $m_e{=}16$', 'sweep100': '100 epochs, $m_e{=}16$'}
rows = []
for cid in LABEL:
    cs = by.get(cid)
    if not cs:
        continue
    rw = med([c.get('recovery_wall_s') for c in cs])
    fr = med([c.get('time_to_first_private_read_s') for c in cs])
    fm = statistics.median(fetched(c) for c in cs)
    rows.append(f"{LABEL[cid]} & {outcome(cid, cs)} & {rw} & {fr} & {fm:.2f} & {len(cs)} \\\\")
hdr = f"% generated by core/experiments/E2/make_compact.py from {' + '.join(sys.argv[1:])} (later files override case ids)"
out = os.path.join(os.path.dirname(os.path.abspath(sys.argv[1])), '..', 'e2_recovery_compact.tex')
open(out, 'w').write(hdr + "\n" + "\n".join(rows) + "\n")
MAIN = ['ok5', 'ok3', 'fail2', 'corrupt3', 'inconsistent', 'precert', 'dropped', 'refuse', 'sweep10']
main_rows = [r for cid, r in zip([c for c in LABEL if by.get(c)], rows) if cid in MAIN]
open(out.replace('compact', 'main'), 'w').write(hdr + " (main-text subset)\n" + "\n".join(main_rows) + "\n")
print(hdr); print("\n".join(rows))
