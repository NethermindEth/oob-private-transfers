"""E2 table + stacked-bar plot from the latest raw file -> core/results/E2/e2_recovery.tex, e2_recovery_breakdown.pdf"""
import json
import statistics as st
from pathlib import Path

R = Path(__file__).resolve().parents[2] / 'results/E2'


def latest():
    """Read the newest uncontaminated run with the default (3,5,5) thresholds."""
    for f in sorted(R.glob('*/e2_raw.json'), reverse=True):
        d = json.loads(f.read_text())
        config = d.get('meta', {}).get('config', {})
        if (config.get('k', 3), config.get('n', 5), config.get('q', 5)) != (3, 5, 5):
            continue
        if not d.get('results') or d.get('meta', {}).get('contaminated'):
            continue
        by = {}
        for row in d['results']:
            by.setdefault(row['case']['id'], []).append(row)
        return [f.parent.name], by
    raise SystemExit('No clean E2 results found. Run core.experiments.E2.run_e2 first.')


def f2(x):
    return '--' if x is None else (f'{x:.3f}' if x < 1 else f'{x:.2f}')


def comps(r):
    """Sum per-stage recovery components over all recovered epochs of one case."""
    eps = [v for v in (r.get('recovery') or {}).get('epochs', {}).values() if 'fetch_s' in v]
    keys = ('fetch_s', 'validate_s', 'decode_s', 'consistency_s', 'u_restore_s', 'pir_rebuild_s')
    c = {k: sum(e.get(k, 0) for e in eps) for k in keys}
    c['certify_check_s'] = sum(e.get('certify_check_s') or 0 for e in eps)
    c['fetch_bytes'] = sum(e.get('fetch_bytes', 0) for e in eps)
    c['temp_bytes'] = max([e.get('temp_bytes', 0) for e in eps] or [0])
    c['n_epochs'] = len(eps)
    return c


def outcome(r):
    rec = r.get('recovery') or {}
    ok = (r.get('read') or {}).get('ok')
    if r.get('error'):
        return 'error'
    if ok:
        return 'recovered, read OK'
    if r.get('reappend_certified') and (r.get('reappend_release') or {}).get('released'):
        return 'lost here; re-append certified, released'
    if (r.get('reappend_read') or {}).get('ok'):
        return 'lost here; re-append read (uncertified)'
    if rec.get('temporarily_unrecoverable'):
        return 'unrecoverable (reported)'
    return 'no certified epoch'


def main():
    used, by = latest()
    order = [('ok5', '5/5 holders'), ('ok4', '4/5 holders'), ('ok3', '3/5 holders'), ('fail2', '2/5 holders'),
             ('corrupt3', '3 corrupted fragments'), ('dupcoord', '3 duplicate coordinates'),
             ('precert', 'failure before certification'), ('dropped', 'provider dropped receipted record'),
             ('holder_replaced', 'holder lost at sealing, set replaced'), ('ok5_fresh', '5/5, no params cache')]
    rows = []
    for cid, lab in order:
        rs = by.get(cid)
        if not rs:
            continue
        cs = [comps(r) for r in rs]
        med = lambda k: st.median([c[k] for c in cs])
        ttf = [r.get('time_to_first_private_read_s') for r in rs if r.get('time_to_first_private_read_s')]
        n = f' (n={len(rs)})' if len(rs) > 1 else ''
        oc = sorted({outcome(r) for r in rs})
        rows.append(f"{lab}{n} & {'; '.join(oc)} & {f2(med('fetch_s') + med('validate_s'))} & "
                    f"{f2(med('decode_s') + med('consistency_s'))} & {f2(med('u_restore_s'))} & {f2(med('pir_rebuild_s'))} & "
                    f"{f2(st.median(ttf)) if ttf else '--'} & {med('fetch_bytes') / 1e6:.2f} \\\\")
    head = ('% generated by core/experiments/E2/make_table.py from ' + ' + '.join(f'results/E2/{t}' for t in used) + ' (later overrides case ids)' +
            '; m_e=4096 records x 736 B; RS(3,5); same-host; replacement sandboxed, empty dir\n'
            'Case & outcome & fetch+validate (s) & decode+check (s) & $U$ restore (s) & PIR rebuild (s) & first read (s) & fetched MB \\\\ \\hline\n')
    (R / 'e2_recovery.tex').write_text(head + '\n'.join(rows) + '\n')
    print((R / 'e2_recovery.tex').read_text())
    # ---- stacked bars: per-stage recovery time, principal cases + epoch-count sweep
    import matplotlib
    matplotlib.use('Agg')
    import matplotlib.pyplot as plt
    cases = [('ok5', '5/5'), ('ok4', '4/5'), ('ok3', '3/5'), ('sweep1', '1 ep.'), ('sweep10', '10 ep.'), ('sweep100', '100 ep.')]
    cases = [(c, l) for c, l in cases if c in by and any((r.get('read') or {}).get('ok') for r in by[c])]
    stages = [('fetch_s', 'fetch', '#222222', ''), ('validate_s', 'validate', '#555555', '//'), ('decode_s', 'decode', '#888888', ''),
              ('consistency_s', 'R_e/codeword check', '#aaaaaa', '..'), ('u_restore_s', 'U restore', '#cccccc', 'xx'),
              ('pir_rebuild_s', 'PIR rebuild', '#eeeeee', '\\\\'), ('other', 'chain waits + other', 'white', '--')]
    fig, ax = plt.subplots(figsize=(5.0, 2.4))
    for x, (cid, lab) in enumerate(cases):
        rs = [r for r in by[cid] if (r.get('read') or {}).get('ok')]
        cs = [comps(r) for r in rs]
        tot = st.median([r['recovery']['total_s'] for r in rs])
        vals = {k: st.median([c[k] for c in cs]) for k, *_ in stages[:-1]}
        vals['other'] = max(0.0, tot - sum(vals.values()))
        bottom = 0
        for k, name, col, hatch in stages:
            ax.bar(x, vals[k], bottom=bottom, color=col, edgecolor='black', hatch=hatch, linewidth=0.5,
                   label=name if x == 0 else None)
            bottom += vals[k]
    ax.set_xticks(range(len(cases)))
    ax.set_xticklabels([l for _, l in cases], fontsize=8)
    ax.set_ylabel('recovery time (s)', fontsize=8)
    ax.tick_params(axis='y', labelsize=8)
    ax.legend(fontsize=6, ncol=2, frameon=False)
    ax.set_title('replacement recovery: 2^12-record epoch by surviving holders; epoch-count sweep (16-rec. epochs)', fontsize=7)
    fig.tight_layout()
    fig.savefig(R / 'e2_recovery_breakdown.pdf')
    print('wrote', R / 'e2_recovery_breakdown.pdf')


if __name__ == '__main__':
    main()
