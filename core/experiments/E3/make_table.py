"""E3 matrix table (LaTeX tabular BODY only) from the latest raw file -> core/results/E3/e3_matrix.tex"""
import json
import statistics as st
from pathlib import Path

R = Path(__file__).resolve().parents[2] / 'results/E3'


def latest():
    import os
    if os.environ.get('OOB_E3_RAW'):  # explicit choice (e.g. a run flagged only for EXTERNAL host load; disclosed)
        f = Path(os.environ['OOB_E3_RAW']).resolve()
        return f, json.loads(f.read_text())
    for f in sorted(R.glob('*/e3_raw.json'), reverse=True):
        d = json.loads(f.read_text())
        if d.get('scenarios') and not d['meta'].get('contaminated') and 'S6_A_replaced_restored_U' in d['scenarios']:
            return f, d
    raise SystemExit('no usable E3 raw file')


def f2(x):
    return '--' if x is None else f'{x:.2f}'


def med(xs):
    xs = [x for x in xs if x is not None]
    return st.median(xs) if xs else None


def main():
    f, d = latest()
    S = d['scenarios']
    rows = []
    s1 = S['S1_write_refused_at_A']
    for mode, lab in (('refuse', 'A refuses write $\\to$ B'), ('delay', 'A delays write ${>}T_w$ $\\to$ B')):
        seq = [x for x in s1 if x['mode'] == mode and x['policy'] == 'sequential']
        hed = [x for x in s1 if x['mode'] == mode and x['policy'] == 'hedged']
        lc = S.get('S1_late_commits_at_A') or {}
        late = lc.get('delay_block' if mode == 'delay' else 'refuse_block', sum(x['alloc_A'] for x in seq + hed))
        rows.append(f"{lab} (seq / hedged) & {len(seq)} / {len(hed)} & {sum(x['complete'] for x in seq)}/{len(seq)} / {sum(x['complete'] for x in hed)}/{len(hed)} & "
                    f"{f2(med([x['latency_s'] for x in seq]))} / {f2(med([x['latency_s'] for x in hed]))} & "
                    f"{f2(max(x['latency_s'] for x in seq + hed))} & {med([x['attempts'] for x in seq])} / {med([x['attempts'] for x in hed])} & "
                    f"A:{late} & {'timeout, yet committed at A' if late else 'no alloc at A'} \\\\")
    s2 = S['S2_repeat_at_A_submit_at_C']
    idem = sum(x['retry'] == 'idempotent' and x['alloc_retry'] == 0 and x['same_receipt'] for x in s2)
    conf = [x for x in s2 if 'conflict' in x]
    atC = sum(x['at_C'] == 'new' and x['alloc_C'] == 1 for x in s2)
    rows.append(f"Repeat at A; submit at C & {len(s2)} & idem {idem}/{len(s2)}, confl {sum(x['conflict'] == 'conflict' for x in conf)}/{len(conf)}, C new {atC} & -- & -- & -- & "
                f"A:{sum(x['alloc_retry'] + x.get('alloc_conflict', 0) for x in s2)} & independent $(e,j)$ at C \\\\")

    def rd(key, lab, note=''):
        xs = S[key]
        ok = sum(x['ok'] for x in xs)
        rows.append(f"{lab} & {len(xs)} & {ok}/{len(xs)} & {f2(med([x['latency_s'] for x in xs]))} & {f2(max(x['latency_s'] for x in xs))} & "
                    f"{med([len(x['attempts']) for x in xs])} & -- & {note} \\\\")
    rd('S3_A_refuses_reads_B_holds', 'A refuses reads; B holds', 'PIR at B')
    xs0, xs1 = S['S4_A_refuses_B_lacks_no_recovery'], S['S4_A_refuses_B_lacks_recipient_recovery']
    rows.append(f"A refuses; B lacks (w/o / with recip. rec.) & {len(xs0)} / {len(xs1)} & {sum(x['ok'] for x in xs0)}/{len(xs0)} / {sum(x['ok'] for x in xs1)}/{len(xs1)} & "
                f"{f2(med([x['latency_s'] for x in xs0]))} / {f2(med([x['latency_s'] for x in xs1]))} & {f2(max(x['latency_s'] for x in xs1))} & "
                f"{med([len(x['attempts']) for x in xs1])} & -- & holders (A3) \\\\")
    rd('S4b_C_refuses_never_anchored', 'C refuses, never anchored (+rec.)', 'no certified copy')
    xs = S['S5_A_delay_reads'] + S['S5_A_malformed_answers']
    al = S['S5_all_refuse_reads']
    rows.append(f"A delay/malformed $\\to$ B; all refuse & {len(xs)} / {len(al)} & {sum(x['ok'] for x in xs)}/{len(xs)} / {sum(x['ok'] for x in al)}/{len(al)} & "
                f"{f2(med([x['latency_s'] for x in xs]))} / {f2(med([x['latency_s'] for x in al]))} & {f2(max(x['latency_s'] for x in xs + al))} & "
                f"{med([len(x['attempts']) for x in xs])} & -- & deadline $T_r{{=}}2$\\,s \\\\")
    s6 = S['S6_A_replaced_restored_U']
    tr = s6['trials']
    rows.append(f"A replaced (new sid), replay & {len(tr)}+1 & idem {sum(t['outcome'] == 'idempotent' for t in tr)}/{len(tr)}, "
                f"confl {int(s6['conflict_after_recovery']['outcome'] == 'conflict')} & -- & -- & -- & "
                f"{sum(t['alloc'] for t in tr) + s6['conflict_after_recovery']['alloc']} & restored $U$ \\\\")
    out = R / 'e3_matrix.tex'
    head = ('% generated by core/experiments/E3/make_table.py from ' + str(f.relative_to(R.parents[1])) +
            '; same-host loopback; injected faults; T_w=T_r=2 s\n'
            'Scenario & trials & completed & median (s) & max (s) & attempts & extra alloc & note \\\\ \\hline\n')
    out.write_text(head + '\n'.join(rows[:8]) + '\n')
    print(out.read_text())


if __name__ == '__main__':
    main()
