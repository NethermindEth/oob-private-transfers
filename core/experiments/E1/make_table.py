"""E1 table (LaTeX tabular BODY only) from the latest (non-contaminated) raw file: core/results/E1/e1_breakdown.tex"""
import json
import statistics as st
import sys
from pathlib import Path

R = Path(__file__).resolve().parents[2] / 'results/E1'


def latest():
    for f in sorted(R.glob('*/e1_raw.json'), reverse=True):
        d = json.loads(f.read_text())
        if d['runs'] and not d['meta'].get('contaminated'):
            return f, d
    raise SystemExit('no usable E1 raw file')


def fmt(x):
    return '--' if x is None else (f'{x:.3f}' if x < 1 else f'{x:.2f}')


def mmm(xs):
    xs = [x for x in xs if x is not None]
    return (st.median(xs), min(xs), max(xs)) if xs else (None, None, None)


def kb(x):
    return '--' if not x else (f'{x / 1e6:.2f}\\,MB' if x >= 1e6 else f'{x / 1e3:.1f}\\,kB')


def main():
    f, d = latest()
    runs = [r for r in d['runs'] if r.get('ok')]
    by = {v: [r for r in runs if r['variant'] == v] for v in ('mmax', 'tmax')}
    a = runs
    rows = []
    def row(name, xs, up=None, down=None):
        m, lo, hi = mmm(xs)
        rows.append(f'{name} & {fmt(m)} & {fmt(lo)} & {fmt(hi)} & {kb(up)} & {kb(down)} \\\\')
    row('Admission proof (client, P1, $d{=}32$)', [r['prepare']['prove_s'] for r in a])
    row('Append: verify + persist + receipt', [r['wall']['append_s'] for r in a],
        st.median([r['append']['attempts'][0]['bytes_up'] for r in a]), st.median([r['append']['attempts'][0]['bytes_down'] for r in a]))
    for v, lab in (('mmax', '$M_{\\max}$'), ('tmax', '$T_{\\max}{=}10$\\,s')):
        if by[v]:
            row(f'Epoch close ({lab}) + PIR preprocessing', [r['read']['epoch_wait_s'] for r in by[v]])
    row('Hint + params download, client load (cold)', [r['read']['download_public_hint_s'] + r['read']['client_load_s'] for r in a],
        None, st.median([r['read']['hint_bytes'] + r['read']['public_bytes'] for r in a]))
    row('PIR query/answer/decode + validate/decrypt/note', [r['read']['query_s'] + r['read']['answer_rtt_s'] + r['read']['recover_s']
        + r['read']['validate_digest_receipt_s'] + r['read']['decrypt_s'] + r['read']['note_check_s'] for r in a],
        st.median([r['read']['query_bytes'] for r in a]), st.median([r['read']['answer_bytes'] for r in a]))
    # The automatic read-policy path, measured in the same runs AFTER the forced PIR read (not in the wall time)
    row('Policy read instead (epoch download + checks)', [r['auto_read_s'] for r in a if r.get('auto_read')],
        None, st.median([r['auto_read']['download_bytes'] for r in a if r.get('auto_read')]))
    for v, lab in (('mmax', '$M_{\\max}$ close'), ('tmax', '$T_{\\max}$ close')):
        if by[v]:
            row(f'\\textbf{{Finality $\\to$ validated note}} ({lab})', [r['wall']['finality_to_validated_note_s'] for r in by[v]])
    rows = rows[:9]
    out = R / 'e1_breakdown.tex'
    head = '% generated by core/experiments/E1/make_table.py from ' + str(f.relative_to(R.parents[1])) + \
           f"; n={len(runs)} runs ({', '.join(f'{k}:{len(v)}' for k, v in by.items())}); same-host loopback\n"
    head += 'Stage & median (s) & min & max & up & down \\\\ \\hline\n'
    out.write_text(head + '\n'.join(rows) + '\n')
    print(out.read_text())


if __name__ == '__main__':
    main()
