"""Compact E5 table for the paper: best (min-client-bytes) layout rows, from raw JSON only.
Usage: python make_compact.py <run_dir> -> core/results/E5pir/e5_reads_compact.tex (tabular body only).
Columns: m & whole-epoch download & hint & q+a (warm read) & cold 1 read & server setup s & answer ms (median) & cheaper"""
import glob, json, os, statistics, sys
run = sys.argv[1]
def fb(n):
    n = float(n)
    return f"{n:.0f}\\,B" if n < 1e3 else f"{n/1e3:.1f}\\,kB" if n < 1e6 else f"{n/1e6:.2f}\\,MB" if n < 1e9 else f"{n/1e9:.2f}\\,GB"
def mlab(m):
    e = m.bit_length() - 1
    return f"$2^{{{e}}}$" if m == 1 << e and m >= 1024 else str(m)
out = []
for f in glob.glob(os.path.join(run, 'pir-N*-best.json')):
    d = json.load(open(f))
    if d['contaminated'] or d['result']['failures'] != 0:
        continue
    r = d['result']; s = r['sizes']; m = r['count']
    ok = [x for x in r['samples'] if x['ok']]
    ans_ms = statistics.median(x['answer_seconds'] for x in ok) * 1e3
    warm = s['query_bytes'] + s['answer_bytes']
    cold = s['public_json_bytes'] + s['hint_bytes'] + warm
    whole = r['baselines']['whole_epoch_download_bytes']
    out.append((m, f"{mlab(m)} & {fb(whole)} & {fb(s['hint_bytes'])} & {fb(warm)} & {fb(cold)} & "
                   f"{r['server_setup']['setup_seconds']:.2f} & {ans_ms:.2f} & {'PIR' if cold < whole else 'download'} \\\\"))
out.sort()
body = [f"% generated by core/experiments/E5pir/make_compact.py from {os.path.basename(run.rstrip('/'))}; best layout; reads/row: see raw"] + [l for _, l in out]
open(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', 'results', 'E5pir', 'e5_reads_compact.tex'), 'w').write("\n".join(body) + "\n")
print("\n".join(body))
